const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('tv', {
  recordHistory: input => ipcRenderer.invoke('history:record', input),
  saveTaste: input => ipcRenderer.invoke('taste:save', input),
  get: () => ipcRenderer.invoke('app:get'),
  openFiles: paths => ipcRenderer.invoke('drop:open', paths),
  seek: (seconds, path) => ipcRenderer.invoke('drop:seek', seconds, path),
  addPoint: (title, path) => ipcRenderer.invoke('drop:add-point', title, path),
  removePoint: (id, path) => ipcRenderer.invoke('drop:remove-point', id, path),
  next: () => ipcRenderer.invoke('drop:next'),
  addFiles: paths => ipcRenderer.invoke('drop:add', paths),
  pause: () => ipcRenderer.invoke('drop:pause'),
  resume: () => ipcRenderer.invoke('drop:resume'),
  stop: () => ipcRenderer.invoke('drop:stop'),
  choose: enqueue => ipcRenderer.invoke('drop:choose', enqueue),
  saveTv: input => ipcRenderer.invoke('settings:tv', input),
  openShuffler: () => ipcRenderer.invoke('shuffler:open'),
  chooseShuffler: kind => ipcRenderer.invoke('shuffler:choose', kind),
  buildShuffler: () => ipcRenderer.invoke('shuffler:build'),
  castPlay: (src, seconds) => ipcRenderer.invoke('channel:play', src, seconds),
  castQueueNext: (src, currentSrc) => ipcRenderer.invoke('channel:queue-next', src, currentSrc),
  getLibrary: () => ipcRenderer.invoke('library:get'),
  libraryArtwork: path => ipcRenderer.invoke('library:artwork', path),
  addLibraryFolder: () => ipcRenderer.invoke('library:add-folder'),
  getAmbient: options => ipcRenderer.invoke('ambient:get', options),
  saveAmbient: options => ipcRenderer.invoke('ambient:save', options),
  chooseAmbientPhotos: () => ipcRenderer.invoke('ambient:photos'),
  startAmbient: options => ipcRenderer.invoke('ambient:start', options),
  cancelAmbient: () => ipcRenderer.invoke('ambient:cancel'),
  onAmbient: listener => ipcRenderer.on('ambient:state', (_event, state) => listener(state)),
  pathFor(file) { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  onState: listener => ipcRenderer.on('drop:state', (_event, state) => listener(state)),
  onCast: listener => ipcRenderer.on('channel:notice', (_event, notice) => listener(notice)),
  onMode: listener => ipcRenderer.on('app:mode', (_event, mode) => listener(mode)),
  onError: listener => ipcRenderer.on('app:error', (_event, message) => listener(message)),
});
